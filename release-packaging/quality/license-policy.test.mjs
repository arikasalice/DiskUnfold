import { strict as assert } from 'node:assert';
import { allowedLicense } from './license-policy.mjs';
const allow = new Set(['MIT','Apache-2.0']);
assert.equal(allowedLicense('MIT', allow), true);
assert.equal(allowedLicense('MIT OR Apache-2.0', allow), true);
assert.equal(allowedLicense('MIT AND CC-BY-3.0', allow), false);
assert.equal(allowedLicense('MIT OR GPL-3.0-only', allow), true);
assert.equal(allowedLicense('MIT AND GPL-3.0-only', allow), false);
assert.equal(allowedLicense('MIT*', allow), false);
assert.equal(allowedLicense('UNLICENSED', allow), false);
assert.equal(allowedLicense(null, allow), false);
console.log('license policy fixtures passed');
