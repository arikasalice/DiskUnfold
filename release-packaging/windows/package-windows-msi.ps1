#Requires -Version 5.1
<#
.SYNOPSIS
Builds the unsigned per-user DiskUnfold MSI that bundles the WebView2 Evergreen Standalone Installer.

.DESCRIPTION
F15 FR9.HD1, install form msi. Verifies the inputs, builds DiskUnfold.wxs with WiX, opens the result
with an administrative extract to check that the packaged executable and documents are the inputs,
checks that the embedded WebView2 installer is the verified input, and writes the manifest.json shape
that du-release-tools reads. It never signs, installs, submits or publishes anything.

The WebView2 installer must be the file Microsoft publishes, unmodified: it is accepted only with a
valid Authenticode signature whose subject is CN=Microsoft Corporation, and its SHA-256 and version are
recorded in the manifest rather than pinned, because Microsoft replaces the file.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string] $BinaryPath,

    [Parameter(Mandatory = $true)]
    [ValidatePattern('^\d+\.\d+\.\d+$')]
    [string] $Version,

    [Parameter(Mandatory = $true)]
    [ValidateSet('x64', 'arm64')]
    [string] $Architecture,

    [Parameter(Mandatory = $true)]
    [string] $OutputDirectory,

    # THIRD-PARTY-NOTICES generated by build-product-resources; it must carry the WebView2 section.
    [Parameter(Mandatory = $true)]
    [string] $NoticesPath,

    # The Evergreen Standalone Installer for the same architecture, as downloaded from Microsoft.
    [Parameter(Mandatory = $true)]
    [string] $WebView2InstallerPath,

    # Where the installer was obtained. Recorded in the manifest.
    [string] $WebView2Source,

    # wix.exe. Defaults to DU_WIX_PATH, then wix on PATH. Its version must equal wix-tool.json.
    [string] $WixPath,

    [string] $IconPath = (Join-Path $PSScriptRoot '..\..\app-host\icons\icon.ico'),

    # Test only: replaces the WebView2 Runtime registry key the package probes, so an installer test
    # can exercise the custom action on a machine that already has the runtime. Never set it for a release.
    [string] $TestOnlyWebView2ClientKey,

    # Test only: skips the Microsoft signature check so a stub installer can be embedded. Requires
    # TestOnlyWebView2ClientKey, and the manifest is not written.
    [switch] $TestOnlySkipWebView2Signature
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'package-common.ps1')

$WebView2ComponentName = 'Microsoft Edge WebView2 Runtime Evergreen Standalone Installer'
$WebView2Links = @{
    x64 = 'https://go.microsoft.com/fwlink/?linkid=2124701'
    arm64 = 'https://go.microsoft.com/fwlink/?linkid=2099616'
}

function Invoke-Native {
    param([Parameter(Mandatory = $true)][string] $Executable, [Parameter(Mandatory = $true)][string[]] $Arguments, [Parameter(Mandatory = $true)][string] $What)

    $output = @(& $Executable @Arguments 2>&1)
    if ($LASTEXITCODE -ne 0) {
        throw ("{0} failed with exit code {1}: {2}" -f $What, $LASTEXITCODE, ($output -join [Environment]::NewLine))
    }
    return $output
}

function Get-Sha256 {
    param([Parameter(Mandatory = $true)][string] $Path)
    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant()
}

function Resolve-Wix {
    $candidate = $WixPath
    if ([string]::IsNullOrWhiteSpace($candidate)) { $candidate = $env:DU_WIX_PATH }
    if ([string]::IsNullOrWhiteSpace($candidate)) {
        $command = Get-Command wix -ErrorAction SilentlyContinue
        if ($command) { $candidate = $command.Source }
    }
    if ([string]::IsNullOrWhiteSpace($candidate)) {
        throw 'wix.exe was not found. Run install-wix.ps1, then pass -WixPath or set DU_WIX_PATH.'
    }
    $resolved = Get-RegularFile -Path $candidate -Description 'wix.exe'
    $pin = Get-Content -LiteralPath (Join-Path $PSScriptRoot 'wix-tool.json') -Raw | ConvertFrom-Json
    $reported = ((Invoke-Native -Executable $resolved -Arguments @('--version') -What 'wix --version') -join '').Trim()
    if (-not $reported.StartsWith($pin.version + '+')) {
        throw "wix.exe reports version $reported but wix-tool.json pins $($pin.version)."
    }
    return $resolved
}

# Returns the verified signer subject of the WebView2 installer or throws.
function Assert-MicrosoftSigned {
    param([Parameter(Mandatory = $true)][string] $Path)

    $signature = Get-AuthenticodeSignature -FilePath $Path
    if ($signature.Status -ne [System.Management.Automation.SignatureStatus]::Valid) {
        throw "The WebView2 installer must have a valid Authenticode signature; status is $($signature.Status)."
    }
    $subject = $signature.SignerCertificate.Subject
    if (-not (@($subject -split ', ') -contains 'CN=Microsoft Corporation')) {
        throw "The WebView2 installer must be signed by CN=Microsoft Corporation; the signer is $subject."
    }
    return $subject
}

$sourceBinary = Get-RegularFile -Path $BinaryPath -Description 'Executable input'
$licensePath = Get-RegularFile -Path (Join-Path $PSScriptRoot '..\..\LICENSE') -Description 'Project license'
$noticesFile = Get-RegularFile -Path $NoticesPath -Description 'THIRD-PARTY-NOTICES input'
$webView2File = Get-RegularFile -Path $WebView2InstallerPath -Description 'WebView2 installer input'
$iconFile = Get-RegularFile -Path $IconPath -Description 'Icon input'
$wxsFile = Get-RegularFile -Path (Join-Path $PSScriptRoot 'DiskUnfold.wxs') -Description 'DiskUnfold.wxs'
$webView2LicenseFile = Get-RegularFile -Path (Join-Path $PSScriptRoot '..\release-tools\data\webview2-license.txt') -Description 'WebView2 license text'
$webView2NoticeFile = Get-RegularFile -Path (Join-Path $PSScriptRoot '..\release-tools\data\webview2-notice.txt') -Description 'WebView2 notice text'

$parsedVersion = [version]::Parse($Version)
if ($parsedVersion.Major -gt 255 -or $parsedVersion.Minor -gt 255 -or $parsedVersion.Build -gt 65535) {
    throw "MSI versions need major and minor from 0 through 255 and build from 0 through 65535: $Version"
}
if ((Get-Item -LiteralPath $noticesFile).Length -eq 0) {
    throw "THIRD-PARTY-NOTICES input is empty: $noticesFile"
}
if (-not ([System.IO.File]::ReadAllText($noticesFile).Contains('WebView2 Runtime (Windows)'))) {
    throw 'THIRD-PARTY-NOTICES has no WebView2 section; regenerate it with this revision of build-product-resources.'
}
if ((Get-PeArchitecture -Path $sourceBinary) -ne $Architecture) {
    throw "Executable architecture does not match the requested $Architecture."
}
# Both standalone installers are 32-bit self-extracting wrappers, so the PE header cannot tell them
# apart; Microsoft's file name carries the architecture.
$expectedInstallerName = if ($Architecture -eq 'x64') { 'MicrosoftEdgeWebView2RuntimeInstallerX64.exe' } else { 'MicrosoftEdgeWebView2RuntimeInstallerARM64.exe' }
if ((Split-Path -Leaf $webView2File) -ine $expectedInstallerName -and -not $TestOnlySkipWebView2Signature) {
    throw "The WebView2 installer for $Architecture must be named $expectedInstallerName."
}
$binarySignature = Get-AuthenticodeSignature -FilePath $sourceBinary
if ($binarySignature.Status -ne [System.Management.Automation.SignatureStatus]::NotSigned) {
    throw "Only unsigned inputs are accepted; Authenticode status is $($binarySignature.Status)."
}

if ($TestOnlySkipWebView2Signature) {
    if ([string]::IsNullOrWhiteSpace($TestOnlyWebView2ClientKey)) {
        throw 'TestOnlySkipWebView2Signature requires TestOnlyWebView2ClientKey.'
    }
    $webView2Signer = 'test stub, not verified'
}
else {
    if (-not [string]::IsNullOrWhiteSpace($TestOnlyWebView2ClientKey)) {
        throw 'TestOnlyWebView2ClientKey is only allowed together with TestOnlySkipWebView2Signature.'
    }
    $webView2Signer = Assert-MicrosoftSigned -Path $webView2File
}
$webView2Version = (Get-Item -LiteralPath $webView2File).VersionInfo.ProductVersion
if ([string]::IsNullOrWhiteSpace($webView2Version) -and $TestOnlySkipWebView2Signature) { $webView2Version = '0.0.0.0' }
if ([string]::IsNullOrWhiteSpace($webView2Version)) {
    throw 'The WebView2 installer has no product version.'
}
$webView2Digest = Get-Sha256 -Path $webView2File
if ([string]::IsNullOrWhiteSpace($WebView2Source)) { $WebView2Source = $WebView2Links[$Architecture] }

$wix = Resolve-Wix

$artifactFileName = 'DiskUnfold-{0}-{1}.msi' -f $Version, $Architecture
$outputFullPath = [System.IO.Path]::GetFullPath($OutputDirectory)
$outputParent = [System.IO.Directory]::GetParent($outputFullPath)
if (-not $outputParent -or -not (Test-Path -LiteralPath $outputParent.FullName -PathType Container)) {
    throw 'The output parent directory must already exist.'
}
Assert-NoReparsePointInPath -Path $outputParent.FullName -Description 'Output parent'
if (Test-Path -LiteralPath $outputFullPath) {
    throw "Output directory already exists; it will not be replaced: $outputFullPath"
}

$stageFullPath = [System.IO.Path]::GetFullPath((Join-Path $outputParent.FullName ('.diskunfold-msi-{0}' -f [guid]::NewGuid().ToString('N'))))
[System.IO.Directory]::CreateDirectory($stageFullPath) | Out-Null
$published = $false

try {
    $inputs = Join-Path $stageFullPath 'inputs'
    [System.IO.Directory]::CreateDirectory($inputs) | Out-Null
    $markerPath = Join-Path $inputs 'install-form'
    Write-Utf8NoBom -Path $markerPath -Contents 'msi'
    $noticePath = Join-Path $inputs 'WEBVIEW2-NOTICE.txt'
    # The license data file starts with "#" lines that record its source; they are not part of the terms.
    $licenseBody = (([System.IO.File]::ReadAllText($webView2LicenseFile).Replace("`r`n", "`n") -split "`n"))
    $firstTerm = 0
    while ($firstTerm -lt $licenseBody.Count -and $licenseBody[$firstTerm].StartsWith('#')) { $firstTerm++ }
    $licenseText = (($licenseBody[$firstTerm..($licenseBody.Count - 1)]) -join "`n").Trim()
    $webView2Text = ([System.IO.File]::ReadAllText($webView2NoticeFile).Replace("`r`n", "`n").TrimEnd() + "`n`n" + $licenseText + "`n")
    Write-Utf8NoBom -Path $noticePath -Contents $webView2Text
    $rtfPath = Join-Path $inputs 'license.rtf'
    [System.IO.File]::WriteAllText($rtfPath, (ConvertTo-Rtf -Text $webView2Text), [System.Text.Encoding]::ASCII)

    $artifactPath = Join-Path $stageFullPath $artifactFileName
    $wixArguments = @(
        'build', '-arch', $Architecture, '-o', $artifactPath,
        '-intermediatefolder', (Join-Path $stageFullPath 'obj'),
        '-d', "Version=$Version",
        '-d', "ExePath=$sourceBinary",
        '-d', "LicensePath=$licensePath",
        '-d', "NoticesPath=$noticesFile",
        '-d', "WebView2NoticePath=$noticePath",
        '-d', "LicenseRtfPath=$rtfPath",
        '-d', "InstallFormPath=$markerPath",
        '-d', "IconPath=$iconFile",
        '-d', "WebView2Path=$webView2File"
    )
    if (-not [string]::IsNullOrWhiteSpace($TestOnlyWebView2ClientKey)) {
        $wixArguments += @('-d', "WebView2ClientKey=$TestOnlyWebView2ClientKey")
    }
    $wixArguments += $wxsFile
    Invoke-Native -Executable $wix -Arguments $wixArguments -What 'wix build' | Out-Null
    if (-not (Test-Path -LiteralPath $artifactPath -PathType Leaf)) {
        throw 'wix build did not produce the MSI.'
    }
    Remove-GeneratedDirectory -Path (Join-Path $stageFullPath 'obj') -ExpectedParent $stageFullPath

    # Open the package with an administrative extract and compare what shipped with what went in.
    $extractPath = Join-Path $stageFullPath 'extract'
    [System.IO.Directory]::CreateDirectory($extractPath) | Out-Null
    $extractLog = Join-Path $stageFullPath 'extract.log'
    # msiexec is a GUI-subsystem program, so only Start-Process -Wait waits for it.
    $extract = Start-Process -FilePath 'msiexec.exe' -ArgumentList @('/a', ('"{0}"' -f $artifactPath), '/qn', ('TARGETDIR="{0}"' -f $extractPath), '/l*v', ('"{0}"' -f $extractLog)) -Wait -PassThru
    if ($extract.ExitCode -ne 0) { throw "administrative extract failed with exit code $($extract.ExitCode)." }
    $members = @{}
    foreach ($name in 'diskunfold.exe', 'LICENSE', 'THIRD-PARTY-NOTICES.txt', 'WEBVIEW2-NOTICE.txt', 'install-form') {
        $found = @(Get-ChildItem -LiteralPath $extractPath -Recurse -File -Filter $name | Where-Object { $_.Name -ceq $name })
        if ($found.Count -ne 1) { throw "The MSI must contain exactly one $name; found $($found.Count)." }
        $members[$name] = $found[0].FullName
    }
    $verifyDirectory = Join-Path $stageFullPath 'verification'
    [System.IO.Directory]::CreateDirectory($verifyDirectory) | Out-Null
    $stagedExecutablePath = Join-Path $verifyDirectory 'diskunfold.exe'
    Copy-Item -LiteralPath $members['diskunfold.exe'] -Destination $stagedExecutablePath
    $executableDigest = Get-Sha256 -Path $stagedExecutablePath
    if ($executableDigest -ne (Get-Sha256 -Path $sourceBinary)) { throw 'The executable in the MSI differs from the input build.' }
    if ((Get-Sha256 -Path $members['LICENSE']) -ne (Get-Sha256 -Path $licensePath)) { throw 'The LICENSE in the MSI differs from the repository file.' }
    if ((Get-Sha256 -Path $members['THIRD-PARTY-NOTICES.txt']) -ne (Get-Sha256 -Path $noticesFile)) { throw 'The notices in the MSI differ from the input.' }
    if ([System.IO.File]::ReadAllText($members['install-form']) -cne 'msi') { throw 'The install-form marker in the MSI is not msi.' }
    Remove-GeneratedDirectory -Path $extractPath -ExpectedParent $stageFullPath

    # The Binary table holds the WebView2 installer; decompiling writes it out so its bytes can be compared.
    $decompilePath = Join-Path $stageFullPath 'decompile'
    Invoke-Native -Executable $wix -Arguments @('msi', 'decompile', '-x', $decompilePath, '-o', (Join-Path $stageFullPath 'decompiled.wxs'), $artifactPath) -What 'wix msi decompile' | Out-Null
    $installerLength = (Get-Item -LiteralPath $webView2File).Length
    $embedded = @(Get-ChildItem -LiteralPath $decompilePath -Recurse -File | Where-Object { $_.Length -eq $installerLength -and (Get-Sha256 -Path $_.FullName) -eq $webView2Digest })
    if ($embedded.Count -ne 1) {
        throw 'The WebView2 installer embedded in the MSI differs from the verified input.'
    }
    Remove-GeneratedDirectory -Path $decompilePath -ExpectedParent $stageFullPath
    Remove-Item -LiteralPath (Join-Path $stageFullPath 'decompiled.wxs'), $extractLog -Force
    Remove-GeneratedDirectory -Path $inputs -ExpectedParent $stageFullPath

    $packageDigest = Get-Sha256 -Path $artifactPath
    $manifest = [ordered]@{
        product_name = 'DiskUnfold'
        version = $Version
        rows = @(
            [ordered]@{
                file_name = $artifactFileName
                version = $Version
                os = [ordered]@{ family = 'windows'; minimum = '11 25H2'; maximum = '11 26H2' }
                cpu = $Architecture
                format = 'msi'
                channel = 'direct'
                signature = 'unsigned'
                signature_scope = 'Unsigned MSI and executable; no SignPath certificate has been applied. The bundled WebView2 installer is unmodified and Authenticode-signed by Microsoft Corporation, which is verified at packaging time.'
                sha256 = $packageDigest
                executable_file_name = 'diskunfold.exe'
                executable_sha256 = $executableDigest
                run_instructions = 'Run the MSI. It needs no administrator rights: it installs DiskUnfold under %LOCALAPPDATA%\Programs\DiskUnfold, adds that folder to your user PATH, and installs the Microsoft Edge WebView2 Runtime only when it is missing. Remove it in Windows Settings, Installed apps; your data folder is kept.'
                bundled_components = @(
                    [ordered]@{
                        name = $WebView2ComponentName
                        version = $webView2Version
                        sha256 = $webView2Digest
                        signer = $webView2Signer
                        source = $WebView2Source
                    }
                )
            }
        )
        channel_references = @()
        staged_files = @(
            [ordered]@{ artifact_file_name = $artifactFileName; kind = 'package'; relative_path = $artifactFileName },
            # Manifest paths use '/' because the release inventory reads them on Linux.
            [ordered]@{ artifact_file_name = $artifactFileName; kind = 'executable'; relative_path = 'verification/diskunfold.exe' }
        )
    }
    if ($TestOnlySkipWebView2Signature) {
        Write-Warning 'Test-only package: the signature check was skipped and no manifest is written.'
    }
    else {
        Write-Utf8NoBom -Path (Join-Path $stageFullPath 'manifest.json') -Contents (ConvertTo-Json -InputObject $manifest -Depth 12)
    }
    if (Test-Path -LiteralPath $outputFullPath) {
        throw "Output directory appeared during packaging; preserving it: $outputFullPath"
    }
    Assert-NoReparsePointInPath -Path $outputParent.FullName -Description 'Output parent changed during packaging'
    [System.IO.Directory]::Move($stageFullPath, $outputFullPath)
    $published = $true
    Write-Output "MSI package: $outputFullPath"
    Write-Output "Artifact: $(Join-Path $outputFullPath $artifactFileName)"
    Write-Output "SHA-256: $packageDigest"
    Write-Output "WebView2 installer: $webView2Version, SHA-256 $webView2Digest, signer $webView2Signer"
    Write-Output 'Signature: unsigned; the WebView2 installer inside is Microsoft-signed.'
}
finally {
    if (-not $published -and (Test-Path -LiteralPath $stageFullPath -PathType Container)) {
        $actualStagePath = [System.IO.Path]::GetFullPath((Get-Item -LiteralPath $stageFullPath -ErrorAction Stop).FullName)
        $parentPrefix = $outputParent.FullName.TrimEnd([System.IO.Path]::DirectorySeparatorChar, [System.IO.Path]::AltDirectorySeparatorChar) + [System.IO.Path]::DirectorySeparatorChar
        if ($actualStagePath -eq $stageFullPath -and $actualStagePath.StartsWith($parentPrefix, [System.StringComparison]::OrdinalIgnoreCase)) {
            Remove-GeneratedDirectory -Path $actualStagePath -ExpectedParent $outputParent.FullName
        }
        else {
            Write-Warning "Preserving staging directory because its identity changed: $stageFullPath"
        }
    }
}
