//! Debian machine-readable copyright file (DEP-5) for the Linux package
//! (F15 FR5.HD1, FR5.HD1.app-host.DD1).
//!
//! The third-party inventory is the one behind THIRD-PARTY-NOTICES: the normal
//! Cargo dependencies of du-launcher plus the production npm packages of
//! gui-web. Packages are grouped by license expression and every license named
//! in an expression gets one standalone paragraph with its canonical SPDX text.

use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write,
    fs,
    path::Path,
};

use spdx::{AdditionItem, Expression, LicenseItem};

use crate::notices::{self, NoticePackage};

#[cfg(test)]
mod tests;

/// Upstream project name.
pub const UPSTREAM_NAME: &str = "DiskUnfold";
/// Upstream contact, identical to the default Debian maintainer.
pub const UPSTREAM_CONTACT: &str = "DiskUnfold Maintainers <arikasalice@gmail.com>";
/// Upstream source location.
pub const UPSTREAM_SOURCE: &str = "https://github.com/arikasalice/DiskUnfold";

const FORMAT_URL: &str = "https://www.debian.org/doc/packaging-manuals/copyright-format/1.0/";
const HEADER_COMMENT: &str = "\
Generated by build-product-resources --debian-copyright from the locked
dependency inventory; do not edit by hand.
The third-party Files patterns are virtual: those packages are compiled into
usr/bin/diskunfold or embedded in its web bundle, so they are not in the
source tree. Cargo packages are the normal dependencies of the launcher on
every target, so the list can include crates that a given platform does not
link. Copyright lines come from the license files bundled with each package,
then from its manifest authors.";

/// One group of packages that share a license expression.
#[derive(Default)]
struct Group {
    files: BTreeSet<String>,
    holders: BTreeSet<String>,
}

/// Licenses and exceptions named by one package expression.
struct Parsed {
    display: String,
    licenses: BTreeSet<String>,
    exceptions: BTreeSet<String>,
}

/// Generates the Debian copyright text for a checkout.
///
/// # Errors
/// Returns a message when the package inventory, the project LICENSE or a license
/// expression cannot be used.
pub fn generate(repo: &Path) -> Result<String, String> {
    let packages = notices::shipped_packages(repo)?;
    let license =
        fs::read_to_string(repo.join("LICENSE")).map_err(|e| format!("read LICENSE: {e}"))?;
    render(&packages, &license)
}

/// Renders the file from a package list and the project LICENSE text.
///
/// The output is sorted, uses LF line endings and has no timestamps or paths.
///
/// # Errors
/// Returns a message when the project license is not the MIT license, or a
/// package has no license or an expression that cannot be expressed in DEP-5.
pub fn render(packages: &[NoticePackage], project_license: &str) -> Result<String, String> {
    let project_holder = project_holder(project_license)?;
    let mut licenses = BTreeSet::from(["MIT".to_owned()]);
    let mut exceptions = BTreeSet::new();
    let mut groups: BTreeMap<String, Group> = BTreeMap::new();
    for package in packages {
        let parsed = parse_expression(package)?;
        licenses.extend(parsed.licenses);
        exceptions.extend(parsed.exceptions);
        let group = groups.entry(parsed.display).or_default();
        group.files.insert(format!(
            "third-party/{}/{}-{}/*",
            package.ecosystem.label(),
            package.name,
            package.version
        ));
        group.holders.extend(holders(package));
    }

    let mut out = String::new();
    field(&mut out, "Format", [FORMAT_URL.to_owned()]);
    field(&mut out, "Upstream-Name", [UPSTREAM_NAME.to_owned()]);
    field(&mut out, "Upstream-Contact", [UPSTREAM_CONTACT.to_owned()]);
    field(&mut out, "Source", [UPSTREAM_SOURCE.to_owned()]);
    field(
        &mut out,
        "Comment",
        HEADER_COMMENT.lines().map(str::to_owned),
    );
    out.push('\n');
    field(&mut out, "Files", ["*".to_owned()]);
    field(&mut out, "Copyright", [project_holder]);
    field(&mut out, "License", ["MIT".to_owned()]);
    for (expression, group) in groups {
        out.push('\n');
        field(&mut out, "Files", group.files);
        field(&mut out, "Copyright", group.holders);
        field(&mut out, "License", [expression]);
    }
    for id in &licenses {
        let license = spdx::license_id(id).ok_or_else(|| format!("unknown SPDX license {id}"))?;
        match common_license(id) {
            Some(file) => common_license_paragraph(&mut out, id, license.full_name, file),
            None => license_paragraph(&mut out, id, license.text()),
        }
    }
    for id in &exceptions {
        let exception =
            spdx::exception_id(id).ok_or_else(|| format!("unknown SPDX exception {id}"))?;
        license_paragraph(&mut out, id, exception.text());
    }
    Ok(out)
}

/// Appends a field whose first value shares the line with the name.
fn field(out: &mut String, name: &str, values: impl IntoIterator<Item = String>) {
    let _ = write!(out, "{name}:");
    for (index, value) in values.into_iter().enumerate() {
        let value = value.trim_end();
        if index == 0 {
            let _ = writeln!(out, " {value}");
        } else if value.is_empty() {
            out.push_str(" .\n");
        } else {
            let _ = writeln!(out, " {value}");
        }
    }
}

/// Returns the file in Debian's /usr/share/common-licenses that holds this
/// license, for the licenses Debian policy says to reference instead of copy.
/// Debian's BSD file is a specific variant, so the BSD licenses keep their text.
fn common_license(id: &str) -> Option<&'static str> {
    let base = id
        .strip_suffix("-or-later")
        .or_else(|| id.strip_suffix("-only"))
        .unwrap_or(id);
    match base {
        "Apache-2.0" => Some("Apache-2.0"),
        "CC0-1.0" => Some("CC0-1.0"),
        "GPL-2.0" => Some("GPL-2"),
        "GPL-3.0" => Some("GPL-3"),
        "LGPL-2.0" => Some("LGPL-2"),
        "LGPL-2.1" => Some("LGPL-2.1"),
        "LGPL-3.0" => Some("LGPL-3"),
        "MPL-1.1" => Some("MPL-1.1"),
        "MPL-2.0" => Some("MPL-2.0"),
        "GFDL-1.2" => Some("GFDL-1.2"),
        "GFDL-1.3" => Some("GFDL-1.3"),
        "Artistic-1.0-Perl" => Some("Artistic"),
        _ => None,
    }
}

/// Appends a standalone License paragraph that points at Debian's copy of the text.
fn common_license_paragraph(out: &mut String, name: &str, full_name: &str, file: &str) {
    out.push('\n');
    field(
        out,
        "License",
        [
            name.to_owned(),
            format!("On Debian systems, the complete text of the {full_name} can be"),
            format!("found in /usr/share/common-licenses/{file}."),
        ],
    );
}

/// Appends a standalone License paragraph with the full text.
fn license_paragraph(out: &mut String, name: &str, text: &str) {
    out.push('\n');
    let lines: Vec<String> = text
        .lines()
        .map(|line| line.trim_end().to_owned())
        .collect();
    let start = lines.iter().position(|l| !l.is_empty()).unwrap_or(0);
    let end = lines
        .iter()
        .rposition(|l| !l.is_empty())
        .map_or(0, |i| i + 1);
    let mut values = vec![name.to_owned()];
    values.extend(lines[start..end].iter().cloned());
    field(out, "License", values);
}

/// Returns the holder of the project copyright from the MIT LICENSE.
fn project_holder(license: &str) -> Result<String, String> {
    if !license.trim_start().starts_with("MIT License") {
        return Err("LICENSE is not the MIT license; update the generator".to_owned());
    }
    license
        .lines()
        .find_map(|line| line.strip_prefix("Copyright (c) "))
        .map(|holder| holder.trim().to_owned())
        .ok_or_else(|| "LICENSE has no Copyright (c) line".to_owned())
}

/// Parses a package expression and names its licenses and exceptions.
fn parse_expression(package: &NoticePackage) -> Result<Parsed, String> {
    let label = format!(
        "{}:{}@{}",
        package.ecosystem.label(),
        package.name,
        package.version
    );
    let raw = package
        .license
        .as_deref()
        .ok_or_else(|| format!("{label} has no license expression"))?;
    // Older crates write OR as a slash; cargo reads that form as OR.
    let spelled = if package.ecosystem == notices::Ecosystem::Cargo {
        raw.replace('/', " OR ")
    } else {
        raw.to_owned()
    };
    let expression =
        Expression::parse(&spelled).map_err(|e| format!("{label}: license {raw}: {e}"))?;
    let mut licenses = BTreeSet::new();
    let mut exceptions = BTreeSet::new();
    for item in expression.requirements() {
        match &item.req.license {
            LicenseItem::Spdx { id, .. } => licenses.insert(id.name.to_owned()),
            LicenseItem::Other(_) => return Err(format!("{label}: non-SPDX license {raw}")),
        };
        match &item.req.addition {
            Some(AdditionItem::Spdx(id)) => exceptions.insert(id.name.to_owned()),
            Some(AdditionItem::Other(_)) => {
                return Err(format!("{label}: non-SPDX exception {raw}"));
            }
            None => false,
        };
    }
    Ok(Parsed {
        display: dep5_form(&spelled).map_err(|e| format!("{label}: {e}"))?,
        licenses,
        exceptions,
    })
}

/// Rewrites an SPDX expression in the DEP-5 spelling. DEP-5 has no parentheses;
/// "(A OR B) AND C" becomes "A or B, and C", where the comma lowers precedence.
fn dep5_form(expression: &str) -> Result<String, String> {
    let mut text = expression.trim().to_owned();
    if let Some(rest) = text.strip_prefix('(')
        && let Some((inner, tail)) = rest.split_once(") AND ")
    {
        text = format!("{inner}, and {tail}");
    }
    if text.contains(['(', ')']) {
        return Err(format!(
            "expression {expression} needs parentheses DEP-5 cannot express"
        ));
    }
    let words: Vec<&str> = text
        .split_whitespace()
        .map(|word| match word {
            "OR" => "or",
            "AND" => "and",
            "WITH" => "with",
            other => other,
        })
        .collect();
    Ok(words.join(" "))
}

/// Copyright statements of a package: its license files, else its authors.
fn holders(package: &NoticePackage) -> BTreeSet<String> {
    let mut found = BTreeSet::new();
    for text in &package.texts {
        let lines: Vec<&str> = text.text.lines().collect();
        for (index, line) in lines.iter().enumerate() {
            let next = lines.get(index + 1).copied().unwrap_or_default();
            found.extend(copyright_line(line, next));
        }
    }
    if found.is_empty() {
        let name = format!(
            "{} {} {}",
            package.ecosystem.label(),
            package.name,
            package.version
        );
        found.insert(if package.authors.is_empty() {
            format!("No copyright statement or author recorded for {name}")
        } else {
            format!("Authors of {name}: {}", package.authors.join(", "))
        });
    }
    found
}

/// Returns a copyright statement line with collapsed spacing, or None for
/// prose and template placeholders. A statement that names only years takes
/// the holder from the next line.
fn copyright_line(line: &str, next: &str) -> Option<String> {
    let mut collapsed = line.split_whitespace().collect::<Vec<_>>().join(" ");
    let lower = collapsed.to_ascii_lowercase();
    let rest = lower.strip_prefix("copyright")?.trim_start();
    let starts_like_notice = rest.starts_with('\u{a9}')
        || rest.starts_with(|c: char| c.is_ascii_digit())
        || rest.get(..3).is_some_and(|p| p == "(c)");
    let placeholder = ["<year>", "[year]", "yyyy", "<owner>", "<copyright holders>"]
        .iter()
        .any(|p| rest.contains(p));
    if !(starts_like_notice && !placeholder && rest.len() > 6) {
        return None;
    }
    if !rest.replace("(c)", "").chars().any(char::is_alphabetic) {
        let holder = next.split_whitespace().collect::<Vec<_>>().join(" ");
        if !holder.is_empty() {
            collapsed = format!("{collapsed} {holder}");
        }
    }
    Some(collapsed)
}
